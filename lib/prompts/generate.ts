export function buildGenerateUserPrompt(
  topic: string,
  angle: string,
  referenceExcerpts: string[],
  requirements?: string
): string {
  const refText = referenceExcerpts.length > 0
    ? `\n\n## 风格参考（以下文案的写作风格值得学习）\n${referenceExcerpts.map((e, i) => `【参考${i + 1}】\n${e}`).join('\n\n')}`
    : '';

  return `## 创作任务
主题：${topic}
角度：${angle}
${requirements ? `\n额外要求：${requirements}` : ''}
${refText}

请撰写一篇完整的视频号文案，字数在 800-1500 字之间。确保风格与参考文案一致，内容围绕主题展开。`;
}

