def audit(text: str) -> dict:
    # 1) LLM 语义审核
    user = f"【合规检查清单】\n{_CHECKLIST}\n\n【待审核口播文案】\n{text}"
    raw = _llm.chat(_AUDIT_SYS, user, temperature=0.2, json_mode=True)
    try:
        rep = json.loads(raw)
    except json.JSONDecodeError:
        rep = {"passed": True, "issues": []}
    rep.setdefault("issues", [])

    # 2) 本地违禁词精确扫描（补充 LLM 可能漏判的关键词）
    local_hits = _scan_banned_words(text)
    if local_hits:
        # 去重：LLM 已报的 quote 不重复加
        llm_quotes = {i.get("quote", "") for i in rep["issues"]}
        for hit in local_hits:
            if hit["quote"] not in llm_quotes:
                rep["issues"].append(hit)
        # 有 high 就不算 passed
        if any(i.get("severity") == "high" for i in rep["issues"]):
            rep["passed"] = False

    return rep


def fix(text: str, highs: list[dict]) -> str:
    listed = "\n".join(
        f"- 【{i.get('rule', '')}】违规片段：{i.get('quote', '')}；改法：{i.get('suggestion', '')}"
        for i in highs
    )
    user = f"【高风险违规清单】\n{listed}\n\n【待修正口播文案】\n{text}"
    return _llm.chat(_FIX_SYS, user, temperature=0.4)


def ensure_compliant(text: str, max_rounds: int = 2, log=None) -> dict:
    """审核→修→复审。high 风险必须修掉才 passed；返回合规文本与最终问题清单。"""
    issues, passed, rounds = [], False, 0
    for r in range(max_rounds + 1):
        rep = audit(text)
        issues = rep.get("issues", [])
        highs = [i for i in issues if i.get("severity") == "high"]
        if not highs:
            passed = True
            break
        if r == max_rounds:
            break
        if log:
            log(f"  合规：发现 {len(highs)} 处高风险，自动修正（第 {r + 1} 轮）...")
        fixed = fix(text, highs)
        if fixed:
            text = fixed
            rounds = r + 1
    return {"text": text, "passed": passed, "rounds": rounds, "issues": issues}
