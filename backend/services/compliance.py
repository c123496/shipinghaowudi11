def _scan_banned_words(text: str) -> list[dict]:
    """本地违禁词精确扫描，返回 issues 列表（格式与 LLM audit 对齐）。"""
    found: list[dict] = []
    seen: set[str] = set()
    for word, category in _BANNED.items():
        if word in text and word not in seen:
            seen.add(word)
            found.append({
                "rule": category,
                "severity": "high",
                "quote": word,
                "reason": f"命中违禁词库关键词「{word}」",
                "suggestion": f"删除或替换「{word}」为不触发审核的表述",
            })
    return found


